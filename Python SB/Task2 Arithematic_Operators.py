"""Module:- Arithematic Operators"""
"Description:- The program demonstrates the operation using Arithematic Operators"

X = 25
Y = 5

Addition = X + Y
Subtraction = X - Y
Division = X / Y
Multiplication = X * Y
Floor_Division = X // Y
Modulus = X % Y
Power = X ** Y

print("-----Arithematic Operators-----")
print(f'Addition of a number: {Addition}')
print(f'Subtraction of a number: {Subtraction}')
print(f'Division of both numbers: {Division}')
print(f'Multiplication of both numbers: {Multiplication}')
print(f'Floor_Division of both numbers: {Floor_Division}')
print(f'Moduls (percentage) of Number: {Modulus}')
print(f'Power of the number: {Power}')
