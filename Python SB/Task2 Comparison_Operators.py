'Module:- Comparison Operators'
'Description :- this program demostrates operations using Comparison Operators'

age_1 = 19
age_2 = 33

Equal_to = age_1 == age_2
Greater_than = age_1 > age_2
Less_than = age_1 < age_2
Less_than_equal = age_1 <= age_2
Greater_than_equal = age_1 >= age_2
Not_equal = age_1 != age_2

print(f'equal_to : {Equal_to}')
print(f'Grater than: {Greater_than}')
print(f'less than: {Less_than}')
print(f'less than or equal to: {Less_than_equal}')
print(f'Greater than or equal to: {Greater_than_equal}')
print(f'Not equal to : {Not_equal}')